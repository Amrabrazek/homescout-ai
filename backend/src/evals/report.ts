import { FeedEvalResult } from './feed.eval';
import { ExpectedFilter } from './metrics';
import { ParseEvalResult } from './parse.eval';
import { RetrievalEvalResult } from './retrieval.eval';

export interface SearchReport {
  generatedAt: Date;
  units: number;
  parse: ParseEvalResult;
  retrieval: RetrievalEvalResult;
  /** Models left out of the retrieval comparison, with the reason. */
  skippedModels: { model: string; reason: string }[];
  feed: FeedEvalResult;
}

const pct = (value: number | null | undefined) =>
  value == null ? 'n/a' : `${Math.round(value * 100)}%`;
const ms = (value: number | null) =>
  value == null ? 'n/a' : `${Math.round(value)} ms`;
const cell = (text: string) => text.replace(/\|/g, '\\|');

export function renderSearchReport(report: SearchReport): string {
  const { parse, retrieval, feed } = report;
  const total = parse.cases.length;
  const regexPass = parse.cases.filter((c) => c.regex.diff.pass).length;
  const llmPass = parse.cases.filter((c) => c.llm?.diff.pass).length;
  const llmLabel = 'model' in parse.llm ? parse.llm.model : null;
  const avg = (values: (number | null)[]) => {
    const known = values.filter((v): v is number => v != null);
    return known.length
      ? known.reduce((a, b) => a + b, 0) / known.length
      : null;
  };

  const lines: string[] = [
    '# Search evals',
    '',
    `Generated by \`npm run eval\` on ${report.generatedAt.toISOString().slice(0, 10)} against the fixed seed (${report.units} units). Fixtures: \`backend/src/evals/fixtures/\`.`,
    '',
    '## Summary',
    '',
    '| Check | Result |',
    '|---|---|',
    `| Query parsing, regex only | ${regexPass}/${total} queries fully right |`,
    llmLabel
      ? `| Query parsing, regex + LLM (${llmLabel}) | ${llmPass}/${total} fully right · p50 ${ms(parse.llmLatencyMs.p50)}, p95 ${ms(parse.llmLatencyMs.p95)} over ${parse.llmLatencyMs.calls} calls |`
      : `| Query parsing, regex + LLM | skipped: ${'skipped' in parse.llm ? parse.llm.skipped : ''} |`,
    `| Semantic ranking, random order (baseline) | ${pct(retrieval.meanBaseRate)} relevant in top ${retrieval.k} |`,
    ...retrieval.models.map((model) => {
      const s = retrieval.summary[model];
      return `| Semantic ranking, ${model} | ${pct(s.meanPrecision)} relevant in top ${retrieval.k} · query embed p50 ${ms(s.queryLatencyMs.p50)}, p95 ${ms(s.queryLatencyMs.p95)} |`;
    }),
    ...report.skippedModels.map(
      (s) => `| Semantic ranking, ${s.model} | skipped: ${s.reason} |`
    ),
    `| "For you", stated preferences only | ${pct(avg(feed.personas.map((p) => p.prefsOnly.hard)))} meet preferences · ${pct(avg(feed.personas.map((p) => p.prefsOnly.taste)))} have the taste |`,
    `| "For you", after ${feed.saves} saves (${feed.model}) | ${pct(avg(feed.personas.map((p) => p.withSaves.hard)))} meet preferences · ${pct(avg(feed.personas.map((p) => p.withSaves.taste)))} have the taste${feed.personas.some((p) => !p.tasteVector) ? ' · ⚠ no taste vector (unit embeddings missing)' : ''} |`,
    '',
    '## Query parsing',
    '',
    'A query passes only when every hard filter is right and nothing extra is set: a wrong filter hides good units. Places count as one set (area, city or region).',
    '',
  ];

  const failures = parse.cases.filter(
    (c) => !c.regex.diff.pass || (c.llm && !c.llm.diff.pass)
  );
  if (failures.length) {
    lines.push(
      ...header([
        'Query',
        'Hard part',
        'Expected',
        'Regex',
        ...(llmLabel ? ['Regex + LLM'] : []),
      ]),
      ...failures.map((c) =>
        row([
          cell(c.query),
          c.note,
          show(c.expected),
          c.regex.diff.pass ? '✅' : `❌ ${show(c.regex.got)}`,
          ...(c.llm
            ? [
                (c.llm.diff.pass ? '✅' : `❌ ${show(c.llm.got)}`) +
                  (c.llm.fellBack ? ' (fell back to regex)' : ''),
              ]
            : []),
        ])
      )
    );
  } else {
    lines.push('Every query parsed right.');
  }

  lines.push(
    '',
    '## Semantic ranking',
    '',
    `Each query is parsed into hard filters; the units that pass are ranked by vector similarity to the leftover text, and the top ${retrieval.k} are checked for the trait the text asks for. The baseline is the share of the filtered pool that has the trait. This compares the vector half of hybrid search only, the half that changes between models.`,
    '',
    ...header([
      'Query',
      'Vector text',
      'Trait',
      'Pool',
      'Baseline',
      ...retrieval.models,
    ]),
    ...retrieval.queries.map((q) =>
      row([
        cell(q.query),
        cell(q.text) || '(none)',
        q.relevantLabel,
        String(q.poolSize),
        pct(q.baseRate),
        ...retrieval.models.map((m) => pct(q.precision[m])),
      ])
    ),
    '',
    '## "For you" feed',
    '',
    `Each persona states preferences, then saves ${feed.saves} units that match them and a taste the preferences can't express. Top ${feed.k} of the feed, before and after the saves:`,
    '',
    '| Persona | Taste | Meets prefs, before → after | Has taste, before → after |',
    '|---|---|---|---|',
    ...feed.personas.map(
      (p) =>
        `| ${p.persona} | ${p.tasteLabel} | ${pct(p.prefsOnly.hard)} → ${pct(p.withSaves.hard)} | ${pct(p.prefsOnly.taste)} → ${pct(p.withSaves.taste)}${p.tasteVector ? '' : ' ⚠'} |`
    ),
    '',
    `**${feed.twoTaste.name}** (no stated preferences, ${feed.saves} saves of each): top ${feed.k} has ${feed.twoTaste.counts.map((c) => `${c.count} ${c.label}`).join(', ')} and ${feed.twoTaste.neither} of neither${feed.twoTaste.tasteVector ? '' : ' ⚠ no taste vector'}. If one taste crowds out the other, or "neither" dominates, multi-interest taste (#50) is worth building.`,
    ''
  );
  return lines.join('\n');
}

function row(cells: string[]): string {
  return `| ${cells.join(' | ')} |`;
}

function header(cells: string[]): string[] {
  return [row(cells), `|${cells.map(() => '---|').join('')}`];
}

function show(filter: ExpectedFilter): string {
  const parts = Object.entries(filter).map(([key, value]) =>
    Array.isArray(value)
      ? `${key}: ${value.join(', ')}`
      : `${key}: ${typeof value === 'number' && value >= 1_000_000 ? `${value / 1_000_000}M` : value}`
  );
  return cell(parts.join('; ') || '(nothing)');
}
